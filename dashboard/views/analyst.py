import pandas as pd
import plotly.graph_objects as go
import streamlit as st
from common import SERIES, data_source_badge, ensure_built, review_card, setup

from src.agents.graph import ask
from src.agents.llm import ollama_status
from src.monitoring import telemetry

setup("AI Analyst", "GameOps Analyst answers with approved, read-only tools and cites the evidence it used.")
if not ensure_built():
    st.stop()
data_source_badge()
llm = ollama_status()
if llm["available"]:
    st.markdown(f'<span class="gp-badge ok">LLM: {llm["model"]} via Ollama (tool calling)</span>', unsafe_allow_html=True)
else:
    st.markdown(f'<span class="gp-badge warn">LLM unavailable - {llm["reason"]}. Using the deterministic planner: '
                'answers are composed from tool outputs, not generated by a language model.</span>', unsafe_allow_html=True)

EXAMPLES = ["What are players complaining about most?", "Which complaints increased in Kingdoms of Ember after patch 1.4?",
            "Summarize the latest negative reviews for Pitch Legends", "Compare complaints between Starfall Arena and Turbo Circuit 26",
            "What issues should developers investigate first?", "Why did negative reviews for Starfall Arena increase after update 2.1?"]
st.session_state.setdefault("chat", [])
cols = st.columns(3)
for i, q in enumerate(EXAMPLES):
    if cols[i % 3].button(q, key=f"ex{i}", width="stretch"):
        st.session_state["pending"] = q


def render(out: dict) -> None:
    lines = [ln.strip() for ln in (out["answer"] or "").split("\n") if ln.strip()]
    st.markdown("\n".join(f"- {ln}" for ln in lines) if len(lines) > 1 else (lines[0] if lines else ""))
    mode = out["mode"] or ""
    st.caption(f"mode: {mode} · {out['latency_ms']:.0f} ms · citations: {len(out['citations'])}")
    for w in out["warnings"]:
        st.warning(w)
    if out["tool_calls"]:
        with st.expander(f"Tool provenance ({len(out['tool_calls'])} calls)"):
            st.dataframe(pd.DataFrame([{"tool": t["tool"], "status": t["status"], "latency_ms": t["latency_ms"],
                                        "args": str(t["args"]), "error": (t["error"] or {}).get("message")} for t in out["tool_calls"]]),
                         hide_index=True, width="stretch")
    res = out.get("tool_results", {})
    for cmp in res.get("compare_feedback_trends", [])[:1]:
        ch = pd.DataFrame(cmp["category_changes"]).dropna(subset=["share_a", "share_b"])
        ch = ch[(ch["share_a"] > 0) | (ch["share_b"] > 0)].sort_values("change_pct_points")
        fig = go.Figure()
        fig.add_bar(y=ch["label"], x=100 * ch["share_a"], orientation="h", name=f"{cmp['period_a']['start']}..{cmp['period_a']['end']}",
                    marker_color=SERIES[0], marker_cornerradius=4)
        fig.add_bar(y=ch["label"], x=100 * ch["share_b"], orientation="h", name=f"{cmp['period_b']['start']}..{cmp['period_b']['end']}",
                    marker_color=SERIES[1], marker_cornerradius=4)
        fig.update_layout(title="Complaint share by period (tool: compare_feedback_trends)", barmode="group", height=420, bargroupgap=0.1,
                          xaxis_title="% of reviews")
        st.plotly_chart(fig, width="stretch")
    ev = [r for s in res.get("search_player_reviews", []) for r in s["reviews"]] + \
         [r for a in res.get("analyze_complaints", []) for r in a["examples"]]
    if ev:
        with st.expander(f"Referenced evidence ({len(ev)} reviews)"):
            for r in ev:
                review_card(r)


for turn in st.session_state["chat"]:
    with st.chat_message("user"):
        st.markdown(turn["q"])
    with st.chat_message("assistant"):
        render(turn["out"])

q = st.chat_input("Ask about player feedback...") or st.session_state.pop("pending", None)
if q:
    with st.chat_message("user"):
        st.markdown(q)
    with st.chat_message("assistant"):
        with st.spinner("Selecting tools and gathering evidence..."):
            out = ask(q)
            telemetry.record_agent(out)
        render(out)
    st.session_state["chat"].append({"q": q, "out": out})
